/* =====================================================
   creamos la TABLA de PAIS
   ===================================================== */
CREATE TABLE PAIS (
    id_pais NUMBER(3)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 9 INCREMENT BY 3),
    nom_pais VARCHAR2(20) NOT NULL,

    CONSTRAINT PAIS_PK PRIMARY KEY (id_pais)
);

/* =====================================================
   creamos la TABLA de TIPO_AUTOMOVIL
   ===================================================== */

CREATE TABLE TIPO_AUTOMOVIL (
    id_tipo CHAR(8) NOT NULL,
    descripcion VARCHAR2(20) NOT NULL,

    CONSTRAINT TIPO_AUTOMOVIL_PK PRIMARY KEY (id_tipo)
);


/* =====================================================
   creamos la TABLA MARCA
   ===================================================== */

CREATE TABLE MARCA (
    id_marca NUMBER(2) NOT NULL,
    descripcion VARCHAR2(20) NOT NULL,

    CONSTRAINT MARCA_PK PRIMARY KEY (id_marca)
);


/* =====================================================
   creamos la TABLA SERVICIO
   ===================================================== */

CREATE TABLE SERVICIO (
    id_servicio NUMBER(3) NOT NULL,
    descripcion VARCHAR2(100) NOT NULL,
    costo NUMBER(7) NOT NULL,

    CONSTRAINT SERVICIO_PK PRIMARY KEY (id_servicio)
);

/* =====================================================
   creamos la TABLA CIUDAD
   ===================================================== */

CREATE TABLE CIUDAD (
    id_ciudad NUMBER(3) NOT NULL,
    nom_ciudad VARCHAR2(20) NOT NULL,
    cod_pais NUMBER(3) NOT NULL,

    CONSTRAINT CIUDAD_PK PRIMARY KEY (id_ciudad),
    CONSTRAINT CIUDAD_FK_PAIS FOREIGN KEY (cod_pais)
        REFERENCES PAIS (id_pais)
);


/* =====================================================
   creamos la TABLA MODELO
   ===================================================== */

CREATE TABLE MODELO (
    id_modelo NUMBER(3) NOT NULL,
    marca_id NUMBER(2) NOT NULL,
    descripcion VARCHAR2(20) NOT NULL,

    CONSTRAINT MODELO_PK PRIMARY KEY (id_modelo),
    CONSTRAINT MODELO_FK_MARCA FOREIGN KEY (marca_id)
        REFERENCES MARCA (id_marca)
);


/* =====================================================
   creamos la TABLA CLIENTE
   ===================================================== */

CREATE TABLE CLIENTE (
    rut NUMBER(8) NOT NULL,
    dv CHAR(1) NOT NULL,
    pnombre VARCHAR2(20) NOT NULL,
    snombre VARCHAR2(20),
    appaterno VARCHAR2(20) NOT NULL,
    apmaterno VARCHAR2(20) NOT NULL,
    telefono VARCHAR2(12),
    email VARCHAR2(40),
    tipo_cli CHAR(1) NOT NULL,

    CONSTRAINT CLIENTE_PK PRIMARY KEY (rut)
);
/* =====================================================
   creamos la TABLA SUCURSAL
   ===================================================== */

CREATE TABLE SUCURSAL (
    id_sucursal CHAR(3) NOT NULL,
    nom_sucursal VARCHAR2(20) NOT NULL,
    calle VARCHAR2(20) NOT NULL,
    num_calle NUMBER(4) NOT NULL,
    cod_ciudad NUMBER(3) NOT NULL,

    CONSTRAINT SUCURSAL_PK PRIMARY KEY (id_sucursal),
    CONSTRAINT SUCURSAL_FK_CIUDAD FOREIGN KEY (cod_ciudad)
        REFERENCES CIUDAD (id_ciudad)
);


/* =====================================================
   creamos la TABLA AUTOMOVIL
   ===================================================== */

CREATE TABLE AUTOMOVIL (
    patente CHAR(6) NOT NULL,
    anio NUMBER(4) NOT NULL,
    cant_puertas NUMBER(1) NOT NULL,
    km NUMBER(8) NOT NULL,
    color VARCHAR2(20) NOT NULL,
    cod_tipo_auto CHAR(8) NOT NULL,
    cod_modelo NUMBER(3) NOT NULL,
    rut_cliente NUMBER(8) NOT NULL,

    CONSTRAINT AUTOMOVIL_PK PRIMARY KEY (patente),

    CONSTRAINT AUTOMOVIL_FK_TIPO FOREIGN KEY (cod_tipo_auto)
        REFERENCES TIPO_AUTOMOVIL (id_tipo),

    CONSTRAINT AUTOMOVIL_FK_MODELO FOREIGN KEY (cod_modelo)
        REFERENCES MODELO (id_modelo),

    CONSTRAINT AUTOMOVIL_FK_CLIENTE FOREIGN KEY (rut_cliente)
        REFERENCES CLIENTE (rut)
);


/* =====================================================
   creamos la TABLA ESTANDAR
   ===================================================== */

CREATE TABLE ESTANDAR (
    p_dcto NUMBER(3) NOT NULL,
    puntaje_fidelidad NUMBER(4) NOT NULL,
    rut NUMBER(8) NOT NULL,

    CONSTRAINT ESTANDAR_PK PRIMARY KEY (rut),
    CONSTRAINT ESTANDAR_FK_CLIENTE FOREIGN KEY (rut)
        REFERENCES CLIENTE (rut)
);


/* =====================================================
   creamos la TABLA PREMIUM
   ===================================================== */

CREATE TABLE PREMIUM (
    p_dcto NUMBER(3) NOT NULL,
    peso_cliente NUMBER(4) NOT NULL,
    premio_cliente NUMBER(10) NOT NULL,
    rut NUMBER(8) NOT NULL,

    CONSTRAINT PREMIUM_PK PRIMARY KEY (rut),
    CONSTRAINT PREMIUM_FK_CLIENTE FOREIGN KEY (rut)
        REFERENCES CLIENTE (rut)
);

/* =====================================================
   creamos la TABLA MECANICO
   ===================================================== */

CREATE TABLE MECANICO (
    cod_mecanico NUMBER(3)
        GENERATED BY DEFAULT AS IDENTITY
        (START WITH 460 INCREMENT BY 7),

    pnombre VARCHAR2(20) NOT NULL,
    snombre VARCHAR2(20),
    appaterno VARCHAR2(20) NOT NULL,
    apmaterno VARCHAR2(20) NOT NULL,
    bono_jefatura NUMBER(10),
    sueldo NUMBER(10) NOT NULL,
    monto_impuestos NUMBER(10) NOT NULL,
    cod_supervisor NUMBER(3),

    CONSTRAINT MECANICO_PK PRIMARY KEY (cod_mecanico),

    CONSTRAINT MECANICO_FK_SUPERVISOR
        FOREIGN KEY (cod_supervisor)
        REFERENCES MECANICO (cod_mecanico)
);

/* =====================================================
   creamos la TABLA MANTENCION
   ===================================================== */

CREATE TABLE MANTENCION (
    num_mantencion NUMBER(8) NOT NULL,
    cod_sucursal CHAR(3) NOT NULL,
    fecha_ingreso DATE NOT NULL,
    fecha_salida DATE,
    patente_auto CHAR(6),
    cod_mecanico NUMBER(3) NOT NULL,
    costo_total NUMBER(8) NOT NULL,
    estado VARCHAR2(15) NOT NULL,

    CONSTRAINT MANTENCION_PK
        PRIMARY KEY (num_mantencion),

    CONSTRAINT MANTENCION_FK_MECANICO
        FOREIGN KEY (cod_mecanico)
        REFERENCES MECANICO (cod_mecanico),

    CONSTRAINT MANTENCION_FK_AUTOMOVIL
        FOREIGN KEY (patente_auto)
        REFERENCES AUTOMOVIL (patente),

    CONSTRAINT MANTENCION_FK_SUCURSAL
        FOREIGN KEY (cod_sucursal)
        REFERENCES SUCURSAL (id_sucursal)
);

/* =====================================================
   creamos la TABLA DETALLE_SERVICIO
   ===================================================== */

CREATE TABLE DETALLE_SERVICIO (
    mantencion_num NUMBER(8) NOT NULL,
    cod_servicio NUMBER(3) NOT NULL,
    descuento_serv NUMBER(3) NOT NULL,
    cantidad NUMBER(2) NOT NULL,

    CONSTRAINT DETALLE_SERVICIO_PK
        PRIMARY KEY (mantencion_num, cod_servicio),

    CONSTRAINT DET_SERV_FK_MANTENCION
        FOREIGN KEY (mantencion_num)
        REFERENCES MANTENCION (num_mantencion),

    CONSTRAINT DET_SERV_FK_SERVICIO
        FOREIGN KEY (cod_servicio)
        REFERENCES SERVICIO (id_servicio)
);

