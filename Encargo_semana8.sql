/* =====================================================
   Resultados del INFORME 1
   Simulacion de rebaja selectiva de impuestos
   ===================================================== */

SELECT
    cod_mecanico AS "ID MECANICO",
    pnombre || ' ' || appaterno AS "NOMBRE MECANICO",
    sueldo AS "SALARIO",
    monto_impuestos AS "IMPUESTO ACTUAL",
    ROUND(monto_impuestos * 0.80) AS "IMPUESTO REBAJADO",
    sueldo - ROUND(monto_impuestos * 0.80)
        AS "SUELDO CON REBAJA IMPUESTOS"
FROM MECANICO
WHERE bono_jefatura IS NULL
  AND monto_impuestos < 40000
ORDER BY monto_impuestos DESC, appaterno ASC;

/* =====================================================
   Resultados del INFORME 2
   Calculo de reajuste salarial del 5%
   ===================================================== */

SELECT
    cod_mecanico AS "IDENTIFICADOR",
    pnombre || ' ' || snombre || ' ' || appaterno AS "MECANICO",
    sueldo AS "SALARIO ACTUAL",
    ROUND(sueldo * 0.05) AS "AJUSTE",
    sueldo + ROUND(sueldo * 0.05) AS "SUELDO_REAJUSTADO"
FROM MECANICO
WHERE sueldo BETWEEN 600000 AND 900000
   OR cod_supervisor IS NULL
ORDER BY sueldo ASC,
         pnombre || ' ' || snombre || ' ' || appaterno DESC;